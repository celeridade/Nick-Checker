/** Render a string with a pixel glyph map into rows of text. */
export function renderPxText(
  text: string,
  font: Record<string, PxGlyph>,
  fill = "#",
  blank = " ",
  gap = " "
): string[] {
  const upper = text.toUpperCase();
  const height = Object.values(font)[0]?.length ?? 7;
  const rows: string[] = new Array(height).fill("");
  for (const ch of upper) {
    const glyph = font[ch] ?? font[" "];
    for (let r = 0; r < height; r++) {
      rows[r] += glyph[r].split("").map((c) => (c === "1" ? fill : blank)).join("") + gap;
    }
  }
  return rows.map((r) => r.replace(/[ ]+$/g, ""));
}
